using ModReverse.Core.Ini;

namespace ModReverse.Tests.Ini;

public sealed class MigotoIniParserTests
{
    [Fact]
    public void ParsePreservesDuplicateAssignmentsAndTheirOrder()
    {
        const string text = """
            [Present]
            run = CommandListCreditInfo
            run = CommandListSkinTexture
            run = CommandList\RabbitFX\Run
            """;

        var document = MigotoIniParser.Parse(text);
        var runs = document.Sections.Single().GetAssignments("run").ToArray();

        Assert.Equal(3, runs.Length);
        Assert.Equal("CommandListCreditInfo", runs[0].Value);
        Assert.Equal("CommandListSkinTexture", runs[1].Value);
        Assert.Equal(@"CommandList\RabbitFX\Run", runs[2].Value);
        Assert.Equal([2, 3, 4], runs.Select(line => line.LineNumber));
    }

    [Fact]
    public void ParseTreatsConditionalExpressionsAsDirectives()
    {
        const string text = """
            [TextureOverrideBody]
            if DRAW_TYPE == 1
                vb0 = ResourceBodyPosition
            else if $body == 2
                handling = skip
            else
                drawindexed = 120390, 3, 0
            endif
            """;

        var section = MigotoIniParser.Parse(text).Sections.Single();
        var directives = section.Lines
            .Where(line => line.Kind == MigotoIniLineKind.Directive)
            .ToArray();

        Assert.Equal(["if", "else if", "else", "endif"], directives.Select(line => line.Directive));
        Assert.Equal("DRAW_TYPE == 1", directives[0].Argument);
        Assert.Equal("$body == 2", directives[1].Argument);
        Assert.Equal(3, section.Assignments.Count());
    }

    [Fact]
    public void ParseGroupsPreambleAndSectionsWithoutLosingCommentsOrBlankLines()
    {
        const string text = """
            ; generated by XXMI

            [Constants]
            global persist $body = 0

            [ResourceBody]
            type = Buffer
            stride = 40 ; position buffer
            filename = BodyPosition.buf
            """;

        var document = MigotoIniParser.Parse(text);

        Assert.Equal(2, document.Sections.Count);
        Assert.Contains(
            document.Preamble.Lines,
            line => line.Kind == MigotoIniLineKind.Comment);
        Assert.Contains(
            document.Preamble.Lines,
            line => line.Kind == MigotoIniLineKind.Blank);

        var resource = document.FindSections("resourcebody").Single();
        Assert.True(resource.TryGetLastValue("stride", out var stride));
        Assert.Equal("40", stride);
        Assert.Equal("; position buffer", resource.GetAssignments("stride").Single().InlineComment);
    }

    [Fact]
    public async Task ParseFileAsyncReadsRealTriggerMechaIniWhenFixtureIsAvailable()
    {
        const string fixture =
            @"E:\Blender\MOD Sample\MOD of Mine\鸣潮\SakuraMod\Trigger-Mecha v1.0\Trigger-Mecha v1.0\10Trigger.ini";

        if (!File.Exists(fixture))
        {
            return;
        }

        var document = await MigotoIniParser.ParseFileAsync(fixture);

        Assert.True(document.Sections.Count >= 40);
        Assert.Contains(
            document.Sections.SelectMany(section => section.GetAssignments("drawindexed")),
            line => line.Value == "120390, 3, 0");
        Assert.Contains(
            document.Sections.SelectMany(section => section.GetAssignments("filename")),
            line => line.Value == "0Trigger1111Position.buf");
    }
}
